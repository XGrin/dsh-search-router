#!/usr/bin/env node
/**
 * Regenerate src/providers/__registry.js from the provider files present in
 * src/providers (skipping _-prefixed files like the registry itself).
 *
 *   node scripts/gen-providers.mjs   (also: npm run providers)
 */
import { readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const dir = join(root, "src", "providers");
const ids = readdirSync(dir).filter((name) => name.endsWith(".js") && !name.startsWith("_")).map((name) => name.slice(0, -3)).sort();

const file = `/**
 * The one generated file in the plugin: the provider table, regenerated by
 * \`npm run providers\` (which \`prepare\` runs on install) from the files in
 * src/providers. Dropping a new provider file in and running that script is
 * the complete add-a-provider workflow; the router discovers the rest.
 */
${ids.map((id) => `import ${id} from "./${id}.js";`).join("\n")}

/** id → provider descriptor, as a synchronous table. */
export const PROVIDERS = {
${ids.map((id) => `  ${id},`).join("\n")}
};

/** Resolve one provider descriptor by id. */
export const loadProvider = (id) => PROVIDERS[id];
`;
writeFileSync(join(dir, "__registry.js"), file);
console.log(`providers registry: ${ids.join(", ")}`);
